import { describe, it, expect, vi, beforeEach } from 'vitest';
import { render, screen, waitFor } from '@testing-library/react';
import userEvent from '@testing-library/user-event';

// Mock the summary client so the component renders a summary deterministically,
// without any network or configured endpoint.
vi.mock('./lib/summary', () => ({
  isSummaryEnabled: () => true,
  fetchPlainLanguageSummary: vi.fn(async () => 'Plain language: this study looks at a treatment for adults.'),
}));

import { StudyDetail } from './components/StudyDetail';
import { messages } from './i18n/strings';
import type { Trial } from './types/trial';

const trial: Trial = {
  nctId: 'NCT02896335',
  title: 'Example Study',
  description: {
    en: 'This is the original, technical registry description with specific clinical terms and thresholds.',
    es: null,
  },
  recruitmentStatus: 'recruiting',
  locations: [{ city: 'Boston', state: 'Massachusetts' }],
  registryUpdateDate: '2026-07-21',
  dataRetrievedAt: '2026-10-24T00:00:00Z',
  contacts: [],
  languageRequirement: { status: 'none_stated', sourceText: null },
  sourceUrl: 'https://clinicaltrials.gov/study/NCT02896335',
  criteria: [],
  dataOrigin: 'live',
};

describe('About this study — AI plain-language summary (B1)', () => {
  beforeEach(() => vi.clearAllMocks());

  it('shows the AI summary with an unreviewed/AI disclaimer', async () => {
    const m = messages.en;
    render(<StudyDetail m={m} locale="en" trial={trial} onBack={() => {}} onPrepare={() => {}} />);

    await waitFor(() => {
      expect(screen.getByText(/Plain language: this study looks at a treatment/)).toBeInTheDocument();
    });
    // Disclaimer must be present and must say it is AI-generated and not reviewed.
    expect(screen.getByText(/generated by AI/i)).toBeInTheDocument();
    expect(screen.getByText(/not been reviewed by a person/i)).toBeInTheDocument();
  });

  it('preserves the full original registry description in a dropdown', async () => {
    const m = messages.en;
    render(<StudyDetail m={m} locale="en" trial={trial} onBack={() => {}} onPrepare={() => {}} />);

    await waitFor(() => expect(screen.getByText(/Plain language:/)).toBeInTheDocument());

    // The original text lives behind the "Full study description" dropdown.
    const toggle = screen.getByText(m.fullDescriptionToggle);
    expect(toggle).toBeInTheDocument();
    await userEvent.click(toggle);
    expect(
      screen.getByText(/original, technical registry description/i),
    ).toBeInTheDocument();
  });
});
